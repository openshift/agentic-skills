#!/usr/bin/env bash
# Behavioural tests for scripts/blast-radius.sh, run against a stubbed `oc`
# so they need no cluster and can run in CI.
#
# The cases that matter are the NEGATIVE ones. Every bug this script has had
# failed the same way: it under-reported impact and said so confidently. A
# test suite that only checks the happy path would have caught none of them.
#
#   - "0 Applications" for an ApplicationSet that owned two (label vs ownerRef)
#   - "No fan-out rule for kind" for a lowercase kind the usage text lists
#   - a forbidden list call rendering as "nothing is affected"
#
# usage: tests/blast-radius/test.sh
set -uo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
SCRIPT="$HERE/../blast-radius.sh"
STUB="$(mktemp -d)"; trap 'rm -rf "$STUB"' EXIT
cp "$HERE/fake-oc" "$STUB/oc"; chmod +x "$STUB/oc"
cp "$HERE/fake-oc" "$STUB/kubectl"; chmod +x "$STUB/kubectl"

pass=0; fail=0

run() { FAKE_MODE="$1" PATH="$STUB:$PATH" bash "$SCRIPT" "${@:2}" 2>&1; }
rc_of() { FAKE_MODE="$1" PATH="$STUB:$PATH" bash "$SCRIPT" "${@:2}" >/dev/null 2>&1; echo $?; }

ok()   { pass=$((pass+1)); printf '  \033[32mPASS\033[0m %s\n' "$1"; }
bad()  { fail=$((fail+1)); printf '  \033[31mFAIL\033[0m %s\n       %s\n' "$1" "$2"; }

expect_contains() { # <desc> <haystack> <needle>
  if printf '%s' "$2" | grep -qF -- "$3"; then ok "$1"; else bad "$1" "expected to contain: $3"; fi
}
expect_missing() {
  if printf '%s' "$2" | grep -qF -- "$3"; then bad "$1" "should NOT contain: $3"; else ok "$1"; fi
}
expect_rc() {
  if [[ "$2" == "$3" ]]; then ok "$1"; else bad "$1" "expected exit $3, got $2"; fi
}

echo "blast-radius.sh behaviour"
echo

# --- regression: ApplicationSet fan-out resolved from ownerReferences ---------
out="$(run ok ApplicationSet eval-set openshift-gitops)"
expect_contains "ApplicationSet counts owned Applications"        "$out" "Applications generated by it: 2"
expect_contains "  ...and names them"                             "$out" "openshift-gitops/owned-a"
expect_missing  "  ...and does not report a bare zero"            "$out" "generated by it: 0"

# --- the label fallback still works for stripped ownerRefs -------------------
out="$(run ok ApplicationSet label-set openshift-gitops)"
expect_contains "label fallback finds label-only Applications"    "$out" "Applications generated by it: 1"

# --- regression: kind matching is case-insensitive ---------------------------
out="$(run ok applicationset eval-set openshift-gitops)"
expect_missing  "lowercase kind does not hit the no-rule branch"  "$out" "No fan-out rule"
expect_contains "lowercase kind resolves normally"                "$out" "Applications generated by it: 2"
out="$(run ok APPLICATIONSETS eval-set openshift-gitops)"
expect_contains "plural/uppercase kind resolves too"              "$out" "Applications generated by it: 2"

# --- a failed lookup must never render as zero -------------------------------
out="$(run rbac ApplicationSet eval-set openshift-gitops)"
expect_contains "forbidden list is reported as undeterminable"    "$out" "COULD NOT DETERMINE"
expect_contains "  ...and says not to read it as zero"            "$out" "UNKNOWN, not as zero"
expect_rc       "  ...and exits 4"  "$(rc_of rbac ApplicationSet eval-set openshift-gitops)" 4

out="$(run rbac AppProject default openshift-gitops)"
expect_contains "forbidden AppProject lookup also flagged"        "$out" "COULD NOT DETERMINE"

# The realistic RBAC shape: the named object reads fine, the cluster-wide list
# does not. The object resolves so the script proceeds, and ONLY the fan-out
# query fails — which is precisely how a zero gets reported as fact. The
# all-calls-forbidden case above does not cover this: there the existence probe
# fails first and flags for a different reason.
out="$(run rbac-list ApplicationSet eval-set openshift-gitops)"
expect_contains "list-only denial is caught"                      "$out" "COULD NOT DETERMINE"
expect_missing  "  ...and no fan-out count is asserted"           "$out" "generated by it: 0"
expect_rc       "  ...and exits 4"  "$(rc_of rbac-list ApplicationSet eval-set openshift-gitops)" 4
out="$(run rbac-list AppProject default openshift-gitops)"
expect_contains "list-only denial caught for AppProject too"      "$out" "COULD NOT DETERMINE"
expect_missing  "  ...and no member count is asserted"            "$out" "Applications in this project: 0"

# --- absent object is distinct from "affects nothing" ------------------------
out="$(run notfound AppProject ghost openshift-gitops)"
expect_contains "absent object says so"                           "$out" "No AppProject named 'ghost'"
expect_contains "  ...and refuses to imply safety"                "$out" "NOT a statement that the change is safe"
expect_missing  "  ...and reports no count"                       "$out" "Applications in this project: 0"
expect_rc       "  ...and exits 0"  "$(rc_of notfound AppProject ghost openshift-gitops)" 0

# --- AppProject does not merge same-named projects across instances ----------
out="$(run ok AppProject default openshift-gitops)"
expect_contains "project scoped to its own namespace"             "$out" "Applications in this project: 4"
expect_contains "  ...and flags the same name elsewhere"          "$out" "different"
expect_contains "  ...naming the other instance's app"            "$out" "team-b-gitops/other-instance"

# --- Application: zero resources is not automatically harmless ---------------
out="$(run ok Application never-synced openshift-gitops)"
expect_contains "never-synced app explains the zero"              "$out" "probably means it never deployed"
out="$(run ok Application web openshift-gitops)"
expect_contains "synced app lists its resources"                  "$out" "Managed resources: 2"
expect_contains "  ...and warns about prune"                      "$out" "prune: true"

# --- unknown kind declines explicitly rather than guessing -------------------
out="$(run ok Widget foo bar)"
expect_contains "unknown kind declines"                           "$out" "No fan-out rule for kind"
expect_contains "  ...and says it was not computed"               "$out" "not computed"

# --- no cluster / usage ------------------------------------------------------
expect_rc "no cluster exits 3"      "$(rc_of nocluster ArgoCD x y)"  3
expect_rc "missing args exits 2"    "$(rc_of ok)"                    2
out="$(run nocluster ArgoCD x y)"
expect_contains "no cluster says state it from manifests"         "$out" "NO CLUSTER REACHABLE"

# --- it must never mutate ----------------------------------------------------
out="$(run ok ArgoCD openshift-gitops openshift-gitops)"
expect_contains "declares itself read-only"                       "$out" "read-only; nothing was modified"
expect_contains "ArgoCD reports owner reconciliation risk"        "$out" "Owned by GitopsService/cluster"

echo
echo "  $pass passed, $fail failed"
[[ "$fail" -eq 0 ]] || exit 1
# A suite that silently runs zero assertions passes. Guard against that too.
[[ "$pass" -ge 30 ]] || { echo "  only $pass assertions ran — expected >= 25" >&2; exit 1; }
echo "  blast-radius.sh behaves as specified"
